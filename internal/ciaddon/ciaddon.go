// Package ciaddon renders, previews, installs, and removes the Conn
// pull-request check, a GitHub Actions workflow at
// .github/workflows/conn-check.yml. Preview writes nothing. Installation
// refuses to overwrite different content, and removal deletes only
// byte-identical Conn content. It never creates credentials, sets secrets or
// variables, commits, pushes, or calls GitHub.
package ciaddon

import (
	"bytes"
	_ "embed"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"runtime/debug"
	"strings"
)

// TargetPath is the workflow path inside the repository.
var TargetPath = filepath.Join(".github", "workflows", "conn-check.yml")

//go:embed templates/conn-check.v1.yml.tmpl
var templateV1 string

// Mode selects installation or removal.
type Mode string

const (
	ModeInstall Mode = "install"
	ModeRemove  Mode = "remove"
)

// Action is what applying a plan does to the workflow file.
type Action string

const (
	ActionCreate    Action = "create"
	ActionUnchanged Action = "unchanged"
	ActionRemove    Action = "remove"
	ActionAbsent    Action = "absent"
	ActionConflict  Action = "conflict"
)

var (
	ErrConflict = errors.New("the Conn check workflow conflicts with an existing file")
	ErrUnsafe   = errors.New("the Conn check workflow target is unsafe")
	// ErrRefRequired means the build has no clean revision to pin.
	ErrRefRequired = errors.New("this conn build has no clean source revision; pass an explicit Conn ref such as a commit SHA")
)

var (
	refPattern    = regexp.MustCompile(`^[A-Za-z0-9._/-]{1,200}$`)
	headerPattern = regexp.MustCompile(`(?m)^# Generated by conn ci install \(template v1\)\. Conn source ([A-Za-z0-9._/-]{1,200})\.$`)
)

// Options configure one rendering.
type Options struct {
	// ConnRef is the Conn source revision the workflow builds.
	ConnRef string
	// Comment adds pull-requests: write and one marker-identified comment.
	Comment bool
}

// Plan is a previewed change to one repository.
type Plan struct {
	Root     string
	Path     string
	Mode     Mode
	Options  Options
	Action   Action
	Content  []byte
	Existing []byte
}

// Render returns the workflow for options.
func Render(options Options) ([]byte, error) {
	if !refPattern.MatchString(options.ConnRef) || strings.HasPrefix(options.ConnRef, "-") || strings.Contains(options.ConnRef, "..") {
		return nil, fmt.Errorf("the Conn ref %q must be a commit SHA or a safe tag or branch name", options.ConnRef)
	}
	permission, env, flag := "", "", ""
	if options.Comment {
		permission = "  pull-requests: write"
		env = "          GITHUB_TOKEN: ${{ github.token }}"
		flag = " --comment"
	}
	replacer := strings.NewReplacer("@@CONN_REF@@", options.ConnRef, "@@COMMENT_FLAG@@", flag)
	content := replacer.Replace(templateV1)
	content = replaceLine(content, "@@PR_WRITE_PERMISSION@@", permission)
	content = replaceLine(content, "@@COMMENT_ENV@@", env)
	return []byte(content), nil
}

// replaceLine replaces a line holding only placeholder, or removes it.
func replaceLine(content, placeholder, value string) string {
	if value == "" {
		return strings.Replace(content, placeholder+"\n", "", 1)
	}
	return strings.Replace(content, placeholder, value, 1)
}

// DefaultRef returns the commit this conn binary was built from. A build
// without VCS information or with uncommitted changes has none.
func DefaultRef() (string, error) {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return "", ErrRefRequired
	}
	revision, modified := "", false
	for _, setting := range info.Settings {
		switch setting.Key {
		case "vcs.revision":
			revision = setting.Value
		case "vcs.modified":
			modified = setting.Value == "true"
		}
	}
	if revision == "" || modified {
		return "", ErrRefRequired
	}
	return revision, nil
}

// installedOptions reads the options of an installed version 1 workflow so
// removal can re-render it exactly.
func installedOptions(content []byte) (Options, bool) {
	match := headerPattern.FindSubmatch(content)
	if match == nil {
		return Options{}, false
	}
	return Options{ConnRef: string(match[1]), Comment: bytes.Contains(content, []byte(" ci check --worktree repo --comment'"))}, true
}

// Preview inspects the target without writing anything. In remove mode the
// options are read from the installed file.
func Preview(root string, mode Mode, options Options) (Plan, error) {
	if mode != ModeInstall && mode != ModeRemove {
		return Plan{}, errors.New("mode must be install or remove")
	}
	resolved, err := resolveRoot(root)
	if err != nil {
		return Plan{}, err
	}
	target, err := safeTarget(resolved, TargetPath)
	if err != nil {
		return Plan{}, err
	}
	existing, readErr := readRegular(target)
	if readErr != nil && !errors.Is(readErr, fs.ErrNotExist) {
		return Plan{}, readErr
	}
	plan := Plan{Root: resolved, Path: target, Mode: mode, Options: options, Existing: existing}
	if mode == ModeRemove {
		if errors.Is(readErr, fs.ErrNotExist) {
			plan.Action = ActionAbsent
			return plan, nil
		}
		installed, ok := installedOptions(existing)
		if !ok {
			plan.Action = ActionConflict
			return plan, nil
		}
		plan.Options = installed
		if plan.Content, err = Render(installed); err != nil {
			plan.Action = ActionConflict
			return plan, nil
		}
		plan.Action = ActionConflict
		if bytes.Equal(existing, plan.Content) {
			plan.Action = ActionRemove
		}
		return plan, nil
	}
	if plan.Content, err = Render(options); err != nil {
		return Plan{}, err
	}
	switch {
	case errors.Is(readErr, fs.ErrNotExist):
		plan.Action = ActionCreate
	case bytes.Equal(existing, plan.Content):
		plan.Action = ActionUnchanged
	default:
		plan.Action = ActionConflict
	}
	return plan, nil
}

// Apply re-reads the target and performs the plan. A file that changed
// since the preview stops it.
func Apply(plan Plan) error {
	current, err := Preview(plan.Root, plan.Mode, plan.Options)
	if err != nil {
		return err
	}
	if current.Action == ActionConflict || current.Action != plan.Action || !bytes.Equal(current.Content, plan.Content) {
		return ErrConflict
	}
	switch current.Action {
	case ActionCreate:
		if err := os.MkdirAll(filepath.Dir(current.Path), 0o755); err != nil {
			return err
		}
		if _, err := safeTarget(current.Root, TargetPath); err != nil {
			return err
		}
		file, err := os.OpenFile(current.Path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
		if err != nil {
			if errors.Is(err, fs.ErrExist) {
				return ErrConflict
			}
			return err
		}
		_, writeErr := file.Write(current.Content)
		closeErr := file.Close()
		if writeErr != nil || closeErr != nil {
			_ = os.Remove(current.Path)
			return errors.Join(writeErr, closeErr)
		}
	case ActionRemove:
		if err := os.Remove(current.Path); err != nil {
			return err
		}
		// Remove the directories only when they are empty.
		_ = os.Remove(filepath.Dir(current.Path))
		_ = os.Remove(filepath.Dir(filepath.Dir(current.Path)))
	}
	return nil
}

// Difference summarizes how an existing file differs from the Conn content:
// lines only in the existing file are prefixed with -, lines only in the
// Conn content with +. At most limit lines are listed.
func Difference(existing, proposed []byte, limit int) []string {
	count := func(lines []string) map[string]int {
		counts := map[string]int{}
		for _, line := range lines {
			counts[line]++
		}
		return counts
	}
	existingLines := strings.Split(strings.ReplaceAll(string(existing), "\r\n", "\n"), "\n")
	proposedLines := strings.Split(string(proposed), "\n")
	inExisting, inProposed := count(existingLines), count(proposedLines)
	var lines []string
	for _, line := range existingLines {
		if inProposed[line] == 0 && len(lines) < limit {
			lines = append(lines, "- "+line)
		}
	}
	for _, line := range proposedLines {
		if inExisting[line] == 0 && len(lines) < limit {
			lines = append(lines, "+ "+line)
		}
	}
	return lines
}

func resolveRoot(root string) (string, error) {
	if root == "" {
		var err error
		if root, err = os.Getwd(); err != nil {
			return "", err
		}
	}
	absolute, err := filepath.Abs(filepath.Clean(root))
	if err != nil {
		return "", err
	}
	resolved, err := filepath.EvalSymlinks(absolute)
	if err != nil {
		return "", fmt.Errorf("resolve the repository root: %w", err)
	}
	if info, err := os.Stat(resolved); err != nil || !info.IsDir() {
		return "", errors.New("the repository root is not a directory")
	}
	return resolved, nil
}

func readRegular(path string) ([]byte, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return nil, err
	}
	if !info.Mode().IsRegular() {
		return nil, fmt.Errorf("%w: %s is not a regular file", ErrUnsafe, path)
	}
	return os.ReadFile(path)
}

// safeTarget resolves relative under root and refuses symlinked parents or
// targets that escape it.
func safeTarget(root, relative string) (string, error) {
	target := filepath.Join(root, relative)
	parent := target
	for {
		if _, err := os.Lstat(parent); err == nil {
			break
		} else if !errors.Is(err, fs.ErrNotExist) {
			return "", err
		}
		next := filepath.Dir(parent)
		if next == parent {
			return "", ErrUnsafe
		}
		parent = next
	}
	resolvedParent, err := filepath.EvalSymlinks(parent)
	if err != nil {
		return "", err
	}
	within, err := filepath.Rel(root, resolvedParent)
	if err != nil || within == ".." || strings.HasPrefix(within, ".."+string(filepath.Separator)) || filepath.IsAbs(within) {
		return "", fmt.Errorf("%w: the target escapes the repository root", ErrUnsafe)
	}
	if info, err := os.Lstat(target); err == nil && info.Mode()&os.ModeSymlink != 0 {
		return "", fmt.Errorf("%w: the target is a symbolic link", ErrUnsafe)
	}
	return target, nil
}

// Prerequisite is one step the human completes outside the installer.
type Prerequisite struct {
	Text    string `json:"text"`
	Command string `json:"command,omitempty"`
}

// PrerequisiteInfo fills the exact commands. Empty values become
// placeholders.
type PrerequisiteInfo struct {
	RepositoryID string
	GitHubRepo   string
	ServerURL    string
}

// Prerequisites lists what the workflow needs before it reports anything.
func Prerequisites(info PrerequisiteInfo) []Prerequisite {
	value := func(v, placeholder string) string {
		if v == "" {
			return placeholder
		}
		return v
	}
	repo, repository := value(info.GitHubRepo, "<owner/name>"), value(info.RepositoryID, "<repository-id>")
	server := info.ServerURL
	if !strings.HasPrefix(server, "https://") {
		server = "<https-url>"
	}
	return []Prerequisite{
		{Text: "A Conn backend reachable from GitHub-hosted runners over HTTPS. A local development server is not reachable unless the team uses a self-hosted runner on the same network."},
		{Text: "The Conn source repository github.com/Juanqu261/conn must be readable from the workflow; the template assumes it is public."},
		{Text: "A Project owner creates the CI credential and stores it as the CONN_CI_TOKEN secret. Agents never create CI credentials.", Command: fmt.Sprintf("conn ci credential create --repository %s --github-secret %s", repository, repo)},
		{Text: "Set the Conn server URL as a repository variable.", Command: fmt.Sprintf("gh variable set CONN_SERVER_URL --body %s --repo %s", server, repo)},
		{Text: "Commit and push the workflow file.", Command: "git add " + filepath.ToSlash(TargetPath) + " && git commit -m \"Add the Conn check\" && git push"},
	}
}
